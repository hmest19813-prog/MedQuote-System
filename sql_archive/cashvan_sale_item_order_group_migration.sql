-- ============================================================
-- الكاش فان — دمج أكتر من صنف بنفس الطلبية الحقيقية (order_group)
--
-- "الطلبية" الحقيقية = زيارة/توصيلة مستقلة لعميل. افتراضياً كل
-- صنف مباع (cashvan_sale_item) طلبية لحالها، وأجرة التوصيل ثابتة
-- (مثلاً 2.5 د.أ) لكل طلبية حقيقية بغض النظر عن عدد الأصناف فيها.
--
-- لما تكون زيارة واحدة فيها أكتر من صنف (مثلاً زبون اشترى صنفين
-- بنفس الزيارة)، بدّمج الأصناف دول بنفس order_group من فورم
-- المبيعات فيُحسبوا كطلبية واحدة فقط (أجرة توصيل مرة واحدة بس).
--
-- شغّل هذا الملف كاملاً دفعة واحدة في Supabase SQL Editor.
-- ============================================================

BEGIN;

ALTER TABLE public.cashvan_sale_items ADD COLUMN IF NOT EXISTS order_group text;

CREATE INDEX IF NOT EXISTS idx_cvsi_order_group ON public.cashvan_sale_items (sale_id, order_group);

INSERT INTO public.changelog_entries (title, description) VALUES
  ('الكاش فان: دمج أصناف الزيارة الواحدة', 'عند تسجيل أو تعديل طلبيات الكاش فان، صار ممكن تدمج صنفين (أو أكتر) ضمن نفس الطلبية كزيارة واحدة فعلية — فيُحسبوا كطلبية واحدة فقط بالتسوية بدل طلبية لكل صنف، وأجرة التوصيل تُطبّق مرة واحدة بس عليهم.');

COMMIT;
