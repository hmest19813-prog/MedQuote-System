-- شغّل هذا الملف كاملاً على Supabase SQL Editor

CREATE TABLE IF NOT EXISTS public.changelog_entries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  description text,
  created_by uuid REFERENCES public.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.changelog_entries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS changelog_select ON public.changelog_entries;
CREATE POLICY changelog_select ON public.changelog_entries FOR SELECT USING (auth.uid() IS NOT NULL);

DROP POLICY IF EXISTS changelog_insert ON public.changelog_entries;
CREATE POLICY changelog_insert ON public.changelog_entries FOR INSERT WITH CHECK (public.get_my_role() = 'admin');

DROP POLICY IF EXISTS changelog_update ON public.changelog_entries;
CREATE POLICY changelog_update ON public.changelog_entries FOR UPDATE USING (public.get_my_role() = 'admin');

DROP POLICY IF EXISTS changelog_delete ON public.changelog_entries;
CREATE POLICY changelog_delete ON public.changelog_entries FOR DELETE USING (public.get_my_role() = 'admin');

