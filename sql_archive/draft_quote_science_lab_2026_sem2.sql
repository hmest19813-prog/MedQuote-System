--     تركتها بند واحد بكمية 15 وضفت الالوان باسم الصنف - يلزم تأكيد التوزيع.
--   * "شرائح فارغة" و"أغطية شرائح": الكمية بالورقة مكتوبة كأرقام مفردة (2، 2) بدون تحديد "علبة/عدد" -> تركتها EACH بكمية 2 لكل بند متل ما هو مكتوب حرفياً، رغم انها عادة بتنباع بعلب فيها عشرات القطع. تأكد قبل الإرسال للمورد.
--   * "مجسم الكرة الارضية": ملاحظة "باللغة الانجليزية" -> أضفتها لاسم الصنف.
--   * "حمض الهيدروكلوريك" و"ماء الجير": الحجم (250ml) مكتوب بعمود الملاحظات بالورقة -> دمجته باسم الصنف لأن حقل notes ما بيظهر بالطباعة.

